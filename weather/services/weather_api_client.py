    def _parse_uv_index(self, data: Dict) -> Optional[int]:
        # 자외선 지수 데이터 파싱
        try:
            items = data["response"]["body"]["items"]

            if not items:
                print("자외선 지수 items가 없음")
                return None

            # items 구조 확인
            items_data = items["item"] if isinstance(items, dict) and "item" in items else items

            if items_data and len(items_data) > 0:
                first_item = items_data[0] if isinstance(items_data, list) else items_data

                # 현재 시간대에 맞는 자외선 지수 필드 선택
                current_hour = datetime.now().hour

                if 0 <= current_hour < 3:
                    uv_field = "h0"
                elif 3 <= current_hour < 6:
                    uv_field = "h3"
                elif 6 <= current_hour < 9:
                    uv_field = "h6"
                elif 9 <= current_hour < 12:
                    uv_field = "h9"
                elif 12 <= current_hour < 15:
                    uv_field = "h12"
                elif 15 <= current_hour < 18:
                    uv_field = "h15"
                elif 18 <= current_hour < 21:
                    uv_field = "h18"
                else:  # 21시 이후
                    uv_field = "h21"

                # 선택된 시간대 자외선 지수 가져오기
                uv_value = first_item.get(uv_field) or first_item.get("today") or first_item.get("h12")

                print(f"현재 시간: {current_hour}시, 선택된 UV 필드: {uv_field}, 값: {uv_value}")

                if uv_value and str(uv_value).replace(".", "").isdigit():
                    return int(float(uv_value))

        except (KeyError, IndexError, ValueError) as e:
            print(f"자외선 지수 파싱 에러: {e}")
            print(f"응답 데이터: {data}")

        return None

